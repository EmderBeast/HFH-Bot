"""Texte des Programms auf Deutsch und Englisch.

Im Code steht der deutsche Text: T('Gespeichert: {path}', path=p). In Englisch kommt die Übersetzung aus EN;
fehlt eine, bleibt der deutsche Text stehen. Die Sprache steht in potbot.ini (language = de oder en).
"""
from __future__ import annotations

import re

LANG = 'de'


def set_lang(lang: str | None) -> str:
    global LANG
    LANG = 'en' if str(lang or '').strip().lower().startswith('e') else 'de'
    return LANG


def T(text: str, /, **kw) -> str:
    if LANG == 'en':
        text = EN.get(text, text)
    return text.format(**kw) if kw else text


def yes(answer: str) -> bool:
    """j / ja / y / yes."""
    return answer.strip().lower()[:1] in ('j', 'y')


