def purpose(p: str) -> str:
    if LANG != 'en':
        return p
    if p in PURPOSE_EN:
        return PURPOSE_EN[p]
    for rx, en in PURPOSE_RX:
        m = rx.match(p)
        if m:
            return en.format(*m.groups())
    return p


